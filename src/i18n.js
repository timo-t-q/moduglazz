let lang = 'en';
const listeners = new Set();

export const t = (key) => STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
export const getLang = () => lang;
export const onLang = (fn) => listeners.add(fn);

export function setLang(next) {
  lang = STRINGS[next] ? next : 'en';
  document.documentElement.lang = lang;
  try { localStorage.setItem('mg-lang', lang); } catch {}
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  listeners.forEach((fn) => fn(lang));
}

export function initLang() {
  let saved = null;
  try { saved = localStorage.getItem('mg-lang'); } catch {}
  const browserSk = (navigator.language || '').toLowerCase().startsWith('sk');
  setLang(saved || (browserSk ? 'sk' : 'en'));
}
